// writes the V1-V5 tables from out/*.txt into src/dance/layouts.js between the VARIANTS markers
import fs from 'fs';
const F = '/Users/aravraja/arav-portfolio/src/dance/layouts.js';
const CAM = JSON.parse(fs.readFileSync(new URL('./cams.json', import.meta.url)));
const tab = (v, m) => JSON.parse(fs.readFileSync(new URL(`./out/${v}-${m}.txt`, import.meta.url), 'utf8').split('\n').find((l) => l.startsWith('TABLE')).slice(6));
const fmt = (T) => '[\n' + T.map((s) => `    [${s.join(', ')}],`).join('\n') + '\n  ]';
let s = '// <VARIANTS> generated by dance-rl/export/designs/crew25-layouts/tools (gen.mjs + embed.mjs); lab only (?crew=V1..V5)\n';
s += '// 25-dancer desktop / 13-dancer phone layout options; slot i = dancer i like L4 (odd right of centre, even left).\n';
s += 'const VT = {\n';
for (const v of Object.keys(CAM)) s += `  ${v}: {\n  D: ${fmt(tab(v, 'desktop'))},\n  P: ${fmt(tab(v, 'phone'))} },\n`;
s += '};\n';
s += 'const variant = (key, name, cam) => [key, { name, ...cam, travel: 1.0, desktopFrame: { top: 112, bottom: 150 },\n';
s += '  slots(portrait, n = 25) { return (portrait && n <= 13 ? VT[key].P : VT[key].D).slice(0, n); } }];\n';
s += 'Object.assign(LAYOUTS, Object.fromEntries([\n';
for (const [v, c] of Object.entries(CAM)) s += `  variant('${v}', ${JSON.stringify(c.name)}, { fov: ${c.fov}, elevation: ${JSON.stringify(c.elevation)} }),\n`;
s += ']));\n// </VARIANTS>\n';
let src = fs.readFileSync(F, 'utf8');
if (src.includes('// <VARIANTS>')) src = src.replace(/\/\/ <VARIANTS>[\s\S]*?\/\/ <\/VARIANTS>\n/, s);
else src = src.replace('export const LAYOUT_KEYS', s + 'export const LAYOUT_KEYS');
fs.writeFileSync(F, src);
console.log('ok');
