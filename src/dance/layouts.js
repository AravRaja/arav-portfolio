// A layout as seen with a crew of n: past 9 dancers its `big` fields (camera) replace the 9-dancer ones.
export function layoutView(L, n) {
  return n > 9 && L.big ? { ...L, ...L.big } : L;
}

// The smallest table with room for n, cut to n (the lab's &n= can ask for any size; the page uses 25 and 13 as built).
function bigSlots(portrait, n) {
  const T = portrait ? (n <= 13 ? L4_P13 : n <= 15 ? L4_P15 : L4_P25) : L4_D25;
  return T.slice(0, n);
}
